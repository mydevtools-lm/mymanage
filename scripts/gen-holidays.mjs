// Writes src/lib/holidays-data.ts: Israel's Jewish holidays, fasts, and its
// memorial and national days, computed with @hebcal/core (Israel's calendar:
// one day of Shmini Atzeret, Yom HaAtzma'ut moved when it meets Shabbat).
//   node scripts/gen-holidays.mjs [fromYear] [toYear]     default 2026 2028
// The app ships the result, so it works offline and needs no calendar
// library at run time. To cover more years, run this again and commit.
import { HebrewCalendar } from "@hebcal/core";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const from = Number(process.argv[2] ?? 2026);
const to = Number(process.argv[3] ?? 2028);
if (!(from <= to) || to - from > 20) {
  console.error("usage: node scripts/gen-holidays.mjs [fromYear] [toYear]");
  process.exit(1);
}

/** hebcal's own names (event.getDesc()), by group. Anything else is left out:
 *  Rosh Chodesh, special Shabbatot, Selichot, Family Day and the like. */
const JEWISH = [
  "Rosh Hashana",
  "Erev Rosh Hashana",
  "Tzom Gedaliah",
  "Erev Yom Kippur",
  "Yom Kippur",
  "Erev Sukkot",
  "Sukkot",
  "Shmini Atzeret",
  "Simchat Torah",
  "Chanukah",
  "Asara B'Tevet",
  "Tu BiShvat",
  "Ta'anit Esther",
  "Erev Purim",
  "Purim",
  "Shushan Purim",
  "Ta'anit Bechorot",
  "Erev Pesach",
  "Pesach",
  "Lag BaOmer",
  "Erev Shavuot",
  "Shavuot",
  "Tzom Tammuz",
  "Erev Tish'a B'Av",
  "Tish'a B'Av",
  "Tu B'Av",
];
const NATIONAL = [
  "Yom HaShoah",
  "Yom HaZikaron",
  "Yom HaAtzma'ut",
  "Yom Yerushalayim",
  "Herzl Day",
  "Yitzhak Rabin Memorial Day",
  "Jabotinsky Day",
  "Sigd",
  "Yom HaAliyah",
  "Swords of Iron War Memorial Day",
];

/** Look-alikes that share a leading name with the ones above. */
const EXCLUDE = [
  "Rosh Hashana LaBehemot",
  "Pesach Sheni",
  "Yom HaAliyah School Observance",
  "Purim Katan",
  "Shushan Purim Katan",
];

const matches = (desc, name) =>
  desc === name || desc.startsWith(name + " ") || desc.startsWith(name + ":");

const groupOf = (desc) => {
  // "Pesach II (CH''M)", "Chanukah: 3 Candles", "Rosh Hashana 5787": the
  // leading name decides.
  if (EXCLUDE.some((name) => matches(desc, name))) return null;
  if (JEWISH.some((name) => matches(desc, name))) return "jewish";
  if (NATIONAL.some((name) => matches(desc, name))) return "national";
  return null;
};

const pad = (n) => String(n).padStart(2, "0");
const rows = [];
for (let year = from; year <= to; year++) {
  const events = HebrewCalendar.calendar({
    year,
    isHebrewYear: false,
    il: true,
    sedrot: false,
    omer: false,
    noRoshChodesh: true,
    noSpecialShabbat: true,
    noMinorFast: false,
    noModern: false,
  });
  for (const e of events) {
    const group = groupOf(e.getDesc());
    if (!group) continue;
    const day = e.getDate().greg();
    rows.push({
      d: `${day.getFullYear()}-${pad(day.getMonth() + 1)}-${pad(day.getDate())}`,
      g: group,
      // hebcal spells it without the yod; the state's own name has it.
      he: e.render("he-x-NoNikud").replace("הזכרון", "הזיכרון"),
      en: e.render("en"),
    });
  }
}
rows.sort((a, b) => a.d.localeCompare(b.d) || a.g.localeCompare(b.g));

const body = rows
  .map(
    (r) =>
      `  { d: ${JSON.stringify(r.d)}, g: ${JSON.stringify(r.g)}, he: ${JSON.stringify(r.he)}, en: ${JSON.stringify(r.en)} },`,
  )
  .join("\n");

const source = `// Generated by scripts/gen-holidays.mjs (@hebcal/core, Israel). Do not edit:
// run the script again to change the years.

export type HolidayGroup = "jewish" | "national";

export interface HolidayRow {
  /** yyyy-MM-dd */
  d: string;
  g: HolidayGroup;
  he: string;
  en: string;
}

export const HOLIDAYS_FROM = "${from}-01-01";
export const HOLIDAYS_TO = "${to}-12-31";

export const HOLIDAYS: HolidayRow[] = [
${body}
];
`;
const out = fileURLToPath(
  new URL("../src/lib/holidays-data.ts", import.meta.url),
);
writeFileSync(out, source);
const count = (g) => rows.filter((r) => r.g === g).length;
console.log(
  `${rows.length} days (${count("jewish")} holiday, ${count("national")} memorial and national) for ${from}–${to} → ${out}`,
);
