const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** 1st, 2nd, 3rd, 4th … 21st, 22nd … */
function ordinal(n: number) {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${n}th`;
  return `${n}${["th", "st", "nd", "rd"][n % 10] ?? "th"}`;
}

